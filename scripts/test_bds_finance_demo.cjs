'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');

const source=fs.readFileSync(path.join(__dirname,'../docs/prototypes/bds-finance-demo.html'),'utf8');
assert.match(source,/<!doctype html>/i);
assert.match(source,/Content-Security-Policy/);
assert.match(source,/OFFLINE SAMPLE DEMO/);
assert.match(source,/No real financial data/);
assert.match(source,/Not ready/);
assert.doesNotMatch(source,/<script[^>]+src=/);
assert.doesNotMatch(source,/fetch\s*\(|localStorage|sessionStorage|indexedDB|XMLHttpRequest/);
const embedded=source.match(/<script id="bds-demo-script">([\s\S]*?)<\/script>/);
assert.ok(embedded,'Self-contained embedded ledger code exists');
const context={window:{}};
new vm.Script(embedded[1],{filename:'bds-finance-demo-inline.js'}).runInNewContext(context,{timeout:4000});
const api=context.window.BDSFinanceDemo;
assert.ok(api,'Pure test surface exposed');
assert.equal(api.yearOf('2026-04-05'),'2025/26');
assert.equal(api.yearOf('2026-04-06'),'2026/27');
assert.equal(api.yearOf('2027-01-15'),'2026/27');
assert.equal(api.yearOf('2027-04-05'),'2026/27');
assert.equal(api.yearOf('2027-04-06'),'2027/28');
assert.throws(()=>api.yearOf('2026-02-30'),/Invalid calendar date/);
assert.throws(()=>api.yearOf('2026-13-01'),/Invalid calendar date/);
assert.throws(()=>api.yearOf('2026-2-01'),/Invalid date/);

const total=api.summarise(api.examples,'2026/27','all','all');
assert.equal(total.income,33700);
assert.equal(total.refunds,1900);
assert.equal(total.fees,2850);
assert.equal(total.expenses,1200);
assert.equal(total.estimates,12000);
assert.equal(total.payouts,17500);
assert.equal(total.outgoings,5950);
assert.equal(total.profit,27750,'No estimate/payout double count');
assert.equal(api.format(total.profit),'£277.50');
const previous=api.summarise(api.examples,'2025/26','all','all');
assert.equal(previous.income,1500);
assert.equal(previous.profit,1500);
const cinema=api.summarise(api.examples,'2026/27','Our Cinema','all');
assert.equal(cinema.income,19000);
assert.equal(cinema.refunds,1900);
assert.equal(cinema.fees,2850);
assert.equal(cinema.profit,14250);
const october=api.summarise(api.examples,'2026/27','all','2026-10');
assert.equal(october.income,11000);
assert.equal(october.estimates,12000);
assert.equal(october.profit,11000);
const candidate=api.normalise({id:'import-sample-11',ref:'test-11',date:'2026-11-04',product:'W.NE',source:'Other',kind:'income',pence:2000,description:'Imaginary purchase'});
let imported=api.merge(api.examples,[api.examples[0],candidate]);
assert.equal(imported.added,1);
assert.equal(imported.skipped,1);
assert.equal(imported.records.length,api.examples.length+1);
let again=api.merge(imported.records,[candidate,api.examples[0]]);
assert.equal(again.added,0,'Repeated JSON imports must be idempotent');
assert.equal(again.skipped,2);
assert.throws(()=>api.merge(api.examples,[{...api.examples[0],pence:99999}]),/Conflicting duplicate reference/);
assert.throws(()=>api.merge(api.examples,[{...api.examples[0],id:'another-import-id',pence:99999}]),/Conflicting duplicate reference/);
const sameProviderDifferentLocalId=api.merge(api.examples,[{...api.examples[0],id:'new-local-duplicate-id'}]);
assert.equal(sameProviderDifferentLocalId.added,0);
assert.equal(sameProviderDifferentLocalId.skipped,1);
assert.throws(()=>api.normalise({...candidate,id:'new-12',date:'2026-02-30'}),/Invalid calendar date/);
assert.throws(()=>api.normalise({...candidate,id:'new-13',pence:-250}),/Amount/);
assert.throws(()=>api.normalise({...candidate,id:'new-14',kind:'secret-money'}),/Unknown/);
assert.throws(()=>api.merge(api.examples,Array(251).fill(candidate)),/Too many entries/);
const spreadsheetAttack=api.normalise({...candidate,id:'csv-example',ref:'csv-example',description:'=HYPERLINK("https://example.com","click")'});
const csv=api.csv([spreadsheetAttack]);
assert.match(csv,/"'=HYPERLINK/,'CSV export defangs spreadsheet formula injection');
assert.match(csv,/"csv-example"/);
assert.match(csv,/excluded-from-profit|revenue/);
console.log('PASS BDS Finance demo: offline single-file, source safety, sample-only, April rollover, revenue/refunds/fees/expenses, estimates/payouts excluded, import idempotency, limits and CSV safety.');
