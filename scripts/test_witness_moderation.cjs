'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const sql=fs.readFileSync('supabase/WITNESS_VOTING_COMMUNITY_REVIEW.sql','utf8');
const ui=fs.readFileSync('assets/case-comment-moderation.js','utf8');
const guard=sql.split('create or replace function public.dd_witness_autohide()')[1]?.split('drop trigger if exists dd_witness_autohide_after_flag')[0]||'';
const moderate=sql.split('create or replace function public.dd_moderate_witness(')[1]?.split('create or replace function public.dd_witness_moderation_queue()')[0]||'';
const queue=sql.split('create or replace function public.dd_witness_moderation_queue()')[1]?.split('-- Privileged trigger helpers')[0]||'';
