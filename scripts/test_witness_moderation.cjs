assert.match(guard,/r\.review_flag_floor\s*>=5/);
assert.match(moderate,/pg_advisory_xact_lock\(hashtext\('witness-flags:'\|\|p_id::text\)\)/);
assert.match(moderate,/review_flag_floor=case when p_action='published'/);
assert.match(moderate,/where f\.report_id=r\.id/);
assert.match(queue,/where r\.status='hidden'/);
assert.match(queue,/not public\.dd_is_comment_moderator\(\)/);
assert.match(queue,/revoke all on function public\.dd_witness_moderation_queue\(\) from public,anon,authenticated/);
assert.match(queue,/grant execute on function public\.dd_witness_moderation_queue\(\) to authenticated/);
assert.doesNotMatch(queue,/returns table\([^)]*author_id/);
assert.doesNotMatch(queue,/returns table\([^)]*reporter_id/);
assert.match(ui,/dd_witness_moderation_queue/);
assert.match(ui,/dd_case_comment_moderation_queue/);
assert.match(ui,/dd_moderate_witness/);
assert.match(ui,/No hidden witness reports to review/);
