'use strict';
// M53: a new cited Nimitz analysis is NOT an additional eyewitness, new physical
// observation, verified extraordinary interpretation or permission to enable ratings.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const data=JSON.parse(read('data/public-person-case-links.json'));
const directory=JSON.parse(read('data/public-people-directory.json'));
const curated=JSON.parse(read('data/curated-historical-cases.json'));
const graphCases=JSON.parse(read('data/evidence-dna-claim-drafts.json'));
const role=require('../assets/person-case-links.js');
const dna=require('../assets/evidence-dna.js');
const allowed=role.parse(data,{personIds:directory.people.map(p=>p.id),caseIds:curated.map(c=>c.id)});
assert.equal(allowed.valid,true,'Entire public person/case ledger must fail closed for bad entries');
assert.equal(allowed.links.length,4,'Four source-attributed entries, not four verified events');
assert.equal(allowed.links.filter(l=>l.caseId==='featured-nimitz-2004').length,2);
assert.equal(allowed.links.filter(l=>l.caseId==='featured-rendlesham-1980').length,2);
assert.equal(role.byCase(allowed,'featured-roswell-1947').length,0);
const fravor=role.byPerson(allowed,'david-fravor')[0];
const knuth=role.byPerson(allowed,'kevin-knuth')[0];
assert.equal(fravor.role,'firsthand-statement');
assert.equal(knuth.role,'published-commentary');
assert.match(knuth.roleLabel,/not a 2004 eyewitness/);
assert.match(knuth.context,/not be counted as an extra eyewitness/);
assert.equal(knuth.eventVerified,false);
assert.equal(knuth.reviewStatus,'editorial-draft');
assert.equal(knuth.source.url,'https://www.mdpi.com/1099-4300/21/10/939');
assert.match(knuth.source.locator,/2\.4\.1/);
const p=directory.people.find(x=>x.id==='kevin-knuth');
assert(p && p.articles.some(a=>a.url===knuth.source.url),'Paper itself also linked on original Who profile');
assert(p.claimEvidence?.[0]?.evidenceReviewSummary?.links.some(l=>l.url===knuth.source.url),'Independent Who evidence explanation retained');
const claims=directory.people.flatMap(p=>p.claimEvidence||[]);
assert.equal(directory.people.length,50);
assert.equal(claims.length,23);
assert.equal(directory.people.filter(p=>p.evidenceScope).length,27);
assert(claims.every(c=>c.status==='source_review_pending'&&c.ratingReadiness.publicationApproval==='withheld'));
assert(claims.every(c=>c.sourceAudit.reviewerSignoff==='not_obtained'));
const graph=dna.buildRelationshipGraph(graphCases.cases,'all',allowed.links);
assert.equal(graph.valid,true);
assert.equal(graph.personCount,4);
assert.equal(graph.documentCount,7);
assert.equal(graph.independentWitnessCount,null);
assert.equal(graph.verifiedCaseToCaseEdges,0);
assert.equal(graph.edges.filter(e=>e.relation==='attributed-public-involvement').length,4);
const nimitz=dna.buildRelationshipGraph(graphCases.cases,'featured-nimitz-2004',allowed.links);
assert.equal(nimitz.personCount,2);
assert.equal(nimitz.documentCount,2);
assert.equal(nimitz.claimCount,0,'Cannot synthesize historical claims merely from a published article');
assert.equal(nimitz.independentWitnessCount,null);
const app=read('assets/people-directory.js');
assert(app.includes('rememberProfileCaseDeparture'));
assert(app.includes("dest.searchParams.set('dd_from','who')"));
assert(app.includes('CASE_RETURN_KEY'));
assert(app.includes('window.DDPeopleDirectoryBack=backToDirectory'));
assert(app.includes('rel="noopener noreferrer"'));
const build=read('scripts/build_public_release.cjs');
assert(build.includes("'public-person-case-links.json'")||build.includes('"public-person-case-links.json"'));
assert(!build.includes('WHO_M53_SOURCE_RETURN_CASE_LINEAGE_2026-11-17.md'));
console.log('M53 PASS: 4 cited person-case associations, Nimitz analysis correctly distinct from firsthand testimony, no verified case/physical evidence, 50/23/27 Who gates and contextual return markers intact.');
