'use strict';
// Source-contract tests only; SQL RLS and anonymous access need rollback QA.
const assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const sql=read('supabase/COMMENT_PUBLIC_READ_PRIVACY_REVIEW.sql');
const nameSql=read('supabase/PUBLIC_USERNAMES_REVIEW.sql');
const cases=read('assets/case-discussions.js');
const news=read('assets/inline-news-comments.js');
const names=read('assets/public-profiles.js');
const commentFeed=sql.split('create or replace function public.dd_public_comments(')[1]?.split('create or replace function public.dd_my_comments(')[0];
const myComments=sql.split('create or replace function public.dd_my_comments(')[1]?.split('create or replace function public.dd_can_flag_comment(')[0];
assert.match(sql,/revoke select on table public\.dd_case_comments from public,anon,authenticated/);
assert.match(sql,/grant insert on table public\.dd_case_comments to authenticated/);
assert.match(sql,/grant execute on function public\.dd_public_comments\(text,integer\) to anon,authenticated/);
assert.match(sql,/grant execute on function public\.dd_my_comments\(integer\) to authenticated/);
assert.match(sql,/grant execute on function public\.dd_can_flag_comment\(uuid\) to authenticated/);
assert.match(sql,/public\.dd_can_flag_comment\(comment_id\)/,'Flagging works without raw SELECT');
assert.ok(commentFeed);
assert.match(commentFeed,/c\.status='approved'/);
assert.match(commentFeed,/p_limit>100/);
assert.match(commentFeed,/is_mine/);
assert.doesNotMatch(commentFeed,/returns table\([^)]*(?:author_id|email)/,'Public read shape leaks account ID');
assert.ok(myComments);
assert.match(myComments,/where c\.author_id=auth\.uid\(\)/,'Private history strictly owner-only');
assert.match(myComments,/Registered account required/);
assert.match(nameSql,/grant execute on function public\.dd_public_aliases\(text,uuid\[\]\) to anon,authenticated/);
assert.match(nameSql,/n\.is_public=true/,'Guest usernames must be opt-in');
assert.match(cases,/\.rpc\('dd_public_comments'/);
assert.match(cases,/\.rpc\('dd_my_comments'/);
assert.doesNotMatch(cases,/\.from\('dd_case_comments'\)\.select/,'Avoid raw direct reads');
assert.match(news,/\.rpc\('dd_public_comments'/);
assert.match(news,/if\(item\.is_mine\)/);
assert.match(names,/\.rpc\('dd_public_aliases'/);
console.log('PASS: public anonymous comment feed hides account IDs, owner history isolated, flagged updates preserved, names opt-in');
