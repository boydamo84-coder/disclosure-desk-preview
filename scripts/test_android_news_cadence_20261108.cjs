'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const main=read('android-test/app/src/main/java/com/disclosuredesk/preview/MainActivity.java');
const worker=read('android-test/app/src/main/java/com/disclosuredesk/preview/DiscoveryWorker.java');
const site=read('index.html');
const ticker=read('assets/news-ticker.js');
assert.match(main,/DiscoveryWorker\.class,30,TimeUnit\.MINUTES/,'Android news uses 30m schedule');
assert.match(main,/DiscoveryWorker\.class,2,TimeUnit\.HOURS/,'Video discovery still uses 2h schedule');
assert.match(main,/ExistingPeriodicWorkPolicy\.UPDATE/,'Migrate prior periodic schedules');
assert.match(main,/cancelUniqueWork\(DiscoveryWorker\.JOB\)/,'Retire original mixed 2h job');
assert.match(main,/syncDiscoverySchedules\(\);/,'Enrol settings on app start/save');
assert.match(worker,/dd_scope/,'Separate News and Video workers');
assert.match(worker,/JOB_NEWS="dd-news-alert-checks"/);
assert.match(worker,/JOB_VIDEOS="dd-video-alert-checks"/);
const siteMatch=site.match(/const DD_NEWS_REMOTES=\[\s*\{url:'([^']+)',label:'GitHub active feed'/);
const appMatch=worker.match(/private static final String NEWS_FEED="([^"]+)"/);
assert(siteMatch&&appMatch&&siteMatch[1]===appMatch[1],'Android and website consume exactly same live publisher-sourced feed');
assert.match(ticker,/root\.ddTickerRefresh\(\)/,'Visible website ticker refresh remains enabled');
console.log('PASS 30-minute Android news + same live website feed, 2-hour video, migration and ticker checks');
