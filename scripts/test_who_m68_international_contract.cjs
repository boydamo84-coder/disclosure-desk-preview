'use strict';
/* M70 curated release: read-only institutional catalogue + source outreach, voting excluded. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const programmes=JSON.parse(read('data/programmes-places-m58.json'));
const tracker=JSON.parse(read('data/public-source-verification.json'));
const who=read('who-is-who.html'),world=read('world-uap-programmes.html');
const scripts=read('assets/who-international-programmes-m68.js');
const digest=read('assets/source-outreach-digest-m68.js');
const sources=read('assets/source-verification.js');
const manifest=read('scripts/build_public_release.cjs');
const config=read('assets/community-test-config.js');
assert.equal(programmes.schemaVersion,1);
assert.equal(programmes.records.length,23);
assert.equal(programmes.total,programmes.records.length);
assert.equal(new Set(programmes.records.map(x=>x.id)).size,23);
const v=programmes.records.find(x=>x.id==='vatican');
assert(v&&v.country==='Vatican City');
assert.match(v.description,/archive|observatory/i);
assert(Array.isArray(v.sources)&&v.sources.length>=2);
assert.equal(programmes.internationalResearchLeads.length,14);
for(const p of programmes.records){
 assert(p.name&&p.country&&p.category);
 assert((p.sources||[]).length>0,'Every entry must have at least one cited source: '+p.name);
}
assert.match(scripts,/internationa[lR]esearchLeads|internationalResearchLeads/);
assert.match(scripts,/fetch\('\/data\/programmes-places-m58\.json'/);
assert.match(scripts,/if\(data\.id==='vatican'\)/);
assert.match(scripts,/countries\.has/,'No Vatican duplicate research-programme entry');
assert.match(who,/id="ddWhoInternationalProgrammes"/);
assert.match(who,/id="ddWhoProgrammeCards"/);
assert.match(who,/id="ddWhoProgrammeLeads"/);
assert.match(who,/who-international-programmes-m68\.js/);
assert.match(world,/id="ddWorldOutreach"/);
assert.match(world,/data-dd-outreach-digest/);
assert.match(who,/data-dd-outreach-digest/);
assert.match(who,/source-outreach-digest-m68\.js/);
assert.match(world,/source-outreach-digest-m68\.js/);
assert.match(digest,/fetch\('\/data\/public-source-verification\.json'/);
assert.match(digest,/\/sources#dd-source-enquiry-/);
assert.match(sources,/doc\.id='dd-source-enquiry-'\+r\.id/);
assert.equal(tracker.schemaVersion,1);
assert.equal(tracker.records.length,5);
assert.equal(tracker.records.filter(x=>x.status==='response_received').length,4);
assert.equal(tracker.records.filter(x=>x.status==='sent_unacknowledged').length,1);
assert.equal(tracker.disclosure.privateMessageIdsPublished,false);
assert(tracker.records.some(x=>/Pentagon/.test(x.agency)));
assert(tracker.records.some(x=>/Arquivo Nacional/.test(x.agency)));
assert(tracker.records.some(x=>/GEP/.test(x.agency)));
assert(tracker.records.some(x=>/Library and Archives Canada/.test(x.agency)));
assert(tracker.records.some(x=>/National Archives and Records Administration/.test(x.agency)));
assert(manifest.includes("'who-international-programmes-m68.js'"));
assert(manifest.includes("'source-outreach-digest-m68.js'"));
assert(manifest.includes("'source-outreach-digest-m68.css'"));
assert.match(config,/whoEvidenceBallots:false/);
assert.equal(fs.existsSync(path.join(root,'data/who-community-approvals-m64.json')),false,'No unpublished voting registry copied into M70 source');
assert.doesNotMatch(who,/who-evidence-ballot-m64\\.(?:js|css)/,'Unreleased ballot code must not be loaded');
assert.match(read('assets/site-adsterra-m02.js'),/const RELEASE_ENABLED=false;/);
for(const s of [scripts,digest])assert.doesNotMatch(s,/(?:localStorage|service_role|createClient|supabase\.|eval\s*\(|new Function)/);
console.log('M68 CONTRACT PASS: 23 documented institutions, Vatican contextualised, 14 original leads (deduplicated by country), 5 public enquiry statuses, deep links, private voting & adverts remain disabled.');
