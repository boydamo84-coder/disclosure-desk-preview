'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const rules=fs.readFileSync('community-rules.html','utf8');
const config=fs.readFileSync('assets/community-test-config.js','utf8');
const html=fs.readFileSync('index.html','utf8');
assert.match(rules,/Current website vs future roadmap:/,'Policy distinguishes shipped vs planned features');
assert.match(rules,/Public witness-report submission, comment discussions, reactions and LIVE hearing rooms are enabled/,'Official-host feature policy');
assert.doesNotMatch(rules,/Witness form saves <strong>private drafts only<\/strong>/,'Outdated private-only beta notice');
assert.match(config,/witnessPublic:enabled/,'Witness feature is gated by official hosts');
assert.match(config,/voting:enabled/,'Voting enabled on official hosts');
assert.match(config,/researchPublishing:false/,'Research publication stays disabled');
for(const x of ['#discussions','#private-chat','id="discussions"','id="private-chat"','not yet live','limited steward','site owner','Accept','Decline','five-distinct-flags'])assert.ok(rules.includes(x),'Missing policy invariant '+x);
assert.match(rules,/Public usernames alone will not automatically make an account discoverable/,'Separate explicit chat opt-in');
assert.match(rules,/not.*ban people for disagreement/,'Stewards cannot censor differing opinions');
assert.match(rules,/deleting a witness report does not reset its rolling 24-hour submission allowance/);
const tabs=html.match(/class="tab(?: active)?" data-tab="/g)||[];
assert.equal(tabs.length,11,'Do not advertise a 12th tab until backend and feature QA are approved');
assert.doesNotMatch(html,/data-tab="discussionsPage"/,'New Discussions tab remains roadmap-only');
console.log('PASS: Community Rules reflect enabled vs future features, creator stewards are limited, chat consent and witness quota are explained, 11 current tabs preserved.');
